import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

// Rebuild from the reviewed SSA table transcription, without a network request:
// node scripts/import-us-names.mjs [--check]
// To refresh the source, review a new snapshot and its provenance together.
const [mode] = process.argv.slice(2);
if ((mode !== undefined && mode !== '--check') || process.argv.length > 3) {
  throw new Error('Usage: node scripts/import-us-names.mjs [--check]');
}

const metadata = JSON.parse(readFileSync(new URL('./data/us-ssa-2025.json', import.meta.url), 'utf8'));
const readSnapshot = (path, expectedHash) => {
  const input = readFileSync(new URL(`./data/${path}`, import.meta.url));
  if (createHash('sha256').update(input).digest('hex') !== expectedHash) {
    throw new Error(`Source checksum mismatch: ${path}. Review the snapshot before updating its metadata.`);
  }
  return input.toString('utf8');
};
const [header, ...lines] = readSnapshot(metadata.snapshot, metadata.sha256).trimEnd().split('\n');
if (header !== 'gender,rank,name,previous_rank,source_table') throw new Error('Unexpected SSA snapshot header');
const rows = lines.map((line, index) => {
  const fields = line.split(',');
  const [gender, rankText, name, previousText, sourceTable] = fields;
  const rank = Number(rankText);
  const previousRank = Number(previousText);
  if (fields.length !== 5 || !['M', 'F'].includes(gender) || !/^[A-Za-z]+$/.test(name)
      || !Number.isSafeInteger(rank) || rank < 1 || rank > 1000
      || !Number.isSafeInteger(previousRank) || previousRank < 1
      || !Object.hasOwn(metadata.sourceTables, sourceTable)) {
    throw new Error(`Invalid SSA row ${index + 2}`);
  }
  const change = previousRank - rank;
  if ((sourceTable === 'same' && Math.abs(change) > 4)
      || (sourceTable === 'increase' && change <= 4)
      || (sourceTable === 'decrease' && change >= -4)) {
    throw new Error(`SSA change-table mismatch at row ${index + 2}`);
  }
  return { gender, rank, name };
});

const names = {};
for (const [gender, key] of [['M', 0], ['F', 1]]) {
  const ranked = rows.filter(row => row.gender === gender).sort((a, b) => a.rank - b.rank);
  if (ranked.length !== 1000 || ranked.some((row, index) => row.rank !== index + 1)
      || new Set(ranked.map(row => row.name)).size !== 1000) {
    throw new Error(`SSA ${gender} snapshot must contain exactly one unique name for every rank 1–1000`);
  }
  names[key] = ranked.map(row => row.name);
  if (names[key].length !== metadata.countPerGender) throw new Error(`Insufficient ${gender} names`);
}

const format = values => Array.from({ length: Math.ceil(values.length / 10) }, (_, i) =>
  `        ${values.slice(i * 10, i * 10 + 10).map(name => `'${name}'`).join(', ')}`
).join(',\n');
const output = `/* Data source: Social Security Administration (SSA), 2025 birth-name rankings */
/* Source data licence (publisher): ${metadata.license} */
/* Source data licence URL: ${metadata.licenseUrl} */
/* Credit (optional): ${metadata.attribution} */
/* URL: ${metadata.url} */
/* Selection: Exactly the published 2025 ranks 1–1000 per gender. */
/* Generation is uniform over the selected names, not weighted by birth frequency. */
/* Pinned source transcription, checksums and methodology: scripts/data/us-ssa-2025.json */
/* Generated by scripts/import-us-names.mjs; do not edit the arrays manually. */
const americanNames = {
    0: [
${format(names[0])}
    ],
    1: [
${format(names[1])}
    ]
};

export default americanNames;
`;
const outputUrl = new URL('../src/names/us.ts', import.meta.url);
if (mode === '--check') {
  if (readFileSync(outputUrl, 'utf8') !== output) throw new Error('US given names differ from the reviewed sources');
  console.log('Verified 1000 US given names per gender against the pinned SSA sources.');
} else {
  writeFileSync(outputUrl, output);
  console.log('Imported 1000 US given names per gender from the pinned SSA sources.');
}
