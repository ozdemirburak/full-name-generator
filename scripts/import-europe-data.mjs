import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [mode] = process.argv.slice(2);
assert.ok((mode === undefined || mode === '--check') && process.argv.length <= 3,
  'Usage: node scripts/import-europe-data.mjs [--check]');
const data = new URL('./data/', import.meta.url);
const format = values => Array.from({ length: Math.ceil(values.length / 10) }, (_, i) =>
  `        ${values.slice(i * 10, i * 10 + 10).map(name => JSON.stringify(name)).join(', ')}`).join(',\n');
const display = name => name.replace(/\p{L}[\p{L}\p{M}]*/gu, word => word[0] + word.slice(1).toLowerCase());

for (const [country, label, files] of [
  ['lv', 'latvian', ['lv-pmlp-2026-names.json', 'lv-archives-surnames.json']],
  ['se', 'swedish', ['se-scb-2022-names.json', 'se-scb-2020-surnames.json']]
]) {
  for (const [index, filename] of files.entries()) {
    const kind = index === 0 ? 'names' : 'surnames';
    const metadata = JSON.parse(readFileSync(new URL(filename, data), 'utf8'));
    const bytes = readFileSync(new URL(metadata.snapshot, data));
    assert.equal(createHash('sha256').update(bytes).digest('hex'), metadata.sha256, `${country}: source checksum mismatch`);
    const [header, ...lines] = bytes.toString('utf8').trimEnd().split('\n');
    assert.equal(header, 'gender\tname\tcount');
    const shared = country === 'se' && kind === 'surnames';
    const genders = shared ? ['*'] : ['0', '1'];
    const rows = lines.map(line => {
      const fields = line.split('\t');
      const [gender, name, count] = fields;
      assert.ok(fields.length === 3 && genders.includes(gender) && /^\d+$/.test(count)
        && Number.isSafeInteger(Number(count)) && Number(count) >= metadata.minimumCount
        && name && name.trim() === name && name.normalize('NFC') === name
        && /^\p{L}[\p{L}\p{M} '\u2019-]*[\p{L}\p{M}]$/u.test(name), 'Invalid European source row');
      return { gender, name, count: Number(count) };
    });
    const pools = genders.map(gender => {
      const selected = rows.filter(row => row.gender === gender);
      assert.equal(selected.length, metadata.counts[gender]);
      assert.deepEqual(selected, [...selected].sort((a, b) => b.count - a.count
        || Buffer.compare(Buffer.from(a.name), Buffer.from(b.name))), 'Source selection order differs');
      const values = selected.map(row => country === 'lv' && kind === 'names' ? display(row.name) : row.name);
      assert.equal(new Set(values).size, values.length, 'Duplicate name after display conversion');
      return values;
    });
    assert.equal(rows.length, pools.reduce((total, pool) => total + pool.length, 0));
    const variable = label + (kind === 'names' ? 'Names' : 'Surnames');
    const array = shared ? `[\n${format(pools[0])}\n]` : `{
    0: [\n${format(pools[0])}\n    ],
    1: [\n${format(pools[1])}\n    ]
}`;
    const output = `/* Data source: ${metadata.source} */
/* Source data licence (publisher): ${metadata.license} */
/* Source data licence URL: ${metadata.licenseUrl} */
/* URL: ${metadata.url} */
/* Credit (optional): ${metadata.attribution} */
/* Selection: ${metadata.selection} */
/* Display: ${metadata.display} */
/* Source details and checksums: scripts/data/${filename} */
/* Generated by scripts/import-europe-data.mjs; do not edit the arrays manually. */
const ${variable} = ${array};

export default ${variable};
`;
    const target = new URL(`../src/${kind}/${country}.ts`, import.meta.url);
    if (mode === '--check') assert.equal(readFileSync(target, 'utf8'), output, `${country} ${kind} differ from the reviewed sources`);
    else writeFileSync(target, output);
  }
}
console.log(`${mode === '--check' ? 'Verified' : 'Imported'} Latvian and Swedish CC0 data.`);
