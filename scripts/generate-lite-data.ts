import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { LITE_SIZE, validateData, validateRegistry } from './lib/data-validation';
import type { DatasetKind } from './lib/data-validation';

const requireData = createRequire(import.meta.url);
const SRC_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');

function countriesFor(kind: DatasetKind): string[] {
  const countries = readdirSync(join(SRC_DIR, kind))
    .filter(file => file.endsWith('.ts'))
    .map(file => file.slice(0, -3))
    .sort();
  if (countries.length === 0 || countries.some(country => !/^[a-z]{2}$/.test(country))) {
    throw new Error(`${kind} must use two-letter lowercase country filenames.`);
  }
  const loaded: unknown = requireData(join(SRC_DIR, `${kind}.ts`));
  const registry = loaded !== null && typeof loaded === 'object'
    ? (loaded as Record<string, unknown>)[kind]
    : undefined;
  const datasets = Object.fromEntries(countries.map(country => [
    country, requireData(join(SRC_DIR, kind, `${country}.ts`)).default as unknown
  ]));
  validateRegistry(registry, kind, datasets);
  return countries;
}

function renderDataset(kind: DatasetKind, country: string): string {
  const sourcePath = join(SRC_DIR, kind, `${country}.ts`);
  // Load the TypeScript module rather than parsing strings with regular expressions.
  const data: unknown = requireData(sourcePath).default;
  validateData(data, kind, country);
  const lite = Array.isArray(data)
    ? data.slice(0, LITE_SIZE)
    : { 0: data[0].slice(0, LITE_SIZE), 1: data[1].slice(0, LITE_SIZE) };
  const source = readFileSync(sourcePath, 'utf8');
  const attribution = (ts.getLeadingCommentRanges(source, 0) ?? [])
    .map(comment => source.slice(comment.pos, comment.end))
    .join('\n');
  if (!attribution) throw new Error(`${kind}/${country} is missing its source attribution.`);
  return `${attribution}\nconst data = ${JSON.stringify(lite, null, 2)};\n\nexport default data;\n`;
}

function renderRegistry(kind: DatasetKind, countries: string[]): string {
  const type = kind === 'names' ? 'Names' : 'Surnames';
  const imports = countries.map(country => `import ${country} from './${kind}-lite/${country}';`);
  return [
    '// Generated by scripts/generate-lite-data.ts. Do not edit.',
    `import type { ${type} } from './${kind}';`,
    `export type { ${type} } from './${kind}';`,
    '',
    ...imports,
    '',
    `export const ${kind}: ${type} = { ${countries.join(', ')} };`,
    ''
  ].join('\n');
}

const namesCountries = countriesFor('names');
const surnameCountries = countriesFor('surnames');
if (namesCountries.join(',') !== surnameCountries.join(',')) {
  throw new Error('First-name and surname datasets must cover the same countries.');
}

// Validate everything before replacing any generated output.
const generated = (['names', 'surnames'] as const).map(kind => ({
  kind,
  files: namesCountries.map(country => ({ country, content: renderDataset(kind, country) })),
  registry: renderRegistry(kind, namesCountries)
}));

for (const { kind, files, registry } of generated) {
  const targetDir = join(SRC_DIR, `${kind}-lite`);
  rmSync(targetDir, { recursive: true, force: true });
  mkdirSync(targetDir, { recursive: true });
  for (const { country, content } of files) {
    writeFileSync(join(targetDir, `${country}.ts`), content);
  }
  writeFileSync(join(SRC_DIR, `${kind}-lite.ts`), registry);
}

console.log(`Generated lite data and registries for ${namesCountries.length} countries (${LITE_SIZE} entries per list).`);
