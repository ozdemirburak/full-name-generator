import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [mode] = process.argv.slice(2);
assert.ok((mode === undefined || mode === '--check') && process.argv.length <= 3,
  'Usage: node scripts/import-pl-data.mjs [--check]');
const dataUrl = new URL('./data/', import.meta.url);
const display = name => name.replace(/\p{L}[\p{L}\p{M}]*/gu, word => word[0] + word.slice(1).toLowerCase());
const format = values => Array.from({ length: Math.ceil(values.length / 10) }, (_, i) =>
  `        ${values.slice(i * 10, i * 10 + 10).map(name => JSON.stringify(name)).join(', ')}`).join(',\n');

for (const kind of ['names', 'surnames']) {
  const filename = `pl-pesel-2026-${kind}.json`;
  const metadata = JSON.parse(readFileSync(new URL(filename, dataUrl), 'utf8'));
  const bytes = readFileSync(new URL(metadata.snapshot, dataUrl));
  assert.equal(createHash('sha256').update(bytes).digest('hex'), metadata.sha256, 'PESEL snapshot checksum mismatch');
  const [header, ...lines] = bytes.toString('utf8').trimEnd().split('\n');
  assert.equal(header, 'gender\tname\tcount');
  const rows = lines.map(line => {
    const fields = line.split('\t');
    const [gender, name, count] = fields;
    assert.ok(fields.length === 3 && /^[01]$/.test(gender) && /^\d+$/.test(count)
      && Number.isSafeInteger(Number(count)) && Number(count) >= 2
      && name && name.trim() === name && name.normalize('NFC') === name
      && /^[\p{L}\p{M} '\u2019-]+$/u.test(name), 'Invalid PESEL source row');
    return { gender: Number(gender), name, count: Number(count) };
  });
  assert.equal(rows.length, 2000);
  const pools = [0, 1].map(gender => {
    const selected = rows.filter(row => row.gender === gender);
    assert.equal(selected.length, 1000);
    const ordered = [...selected].sort((a, b) => b.count - a.count || Buffer.compare(Buffer.from(a.name), Buffer.from(b.name)));
    assert.deepEqual(selected, ordered, 'PESEL selections must follow count and UTF-8 spelling order');
    const names = selected.map(row => display(row.name));
    assert.equal(new Set(names).size, 1000, 'Display casing must not merge source names');
    return names;
  });
  const output = `/* Data source: ${metadata.source} */
/* Source data licence (publisher): ${metadata.license} */
/* Source data licence URL: ${metadata.licenseUrl} */
/* URL: ${metadata.url} */
/* Credit (optional): ${metadata.attribution} */
/* Selection: ${metadata.selection} */
/* Display: ${metadata.display} */
/* Source details and checksums: scripts/data/${filename} */
/* Generated by scripts/import-pl-data.mjs; do not edit the arrays manually. */
const polish${kind === 'names' ? 'Names' : 'Surnames'} = {
    0: [
${format(pools[0])}
    ],
    1: [
${format(pools[1])}
    ]
};

export default polish${kind === 'names' ? 'Names' : 'Surnames'};
`;
  const target = new URL(`../src/${kind}/pl.ts`, import.meta.url);
  if (mode === '--check') assert.equal(readFileSync(target, 'utf8'), output, `Polish ${kind} differ from the reviewed sources`);
  else writeFileSync(target, output);
}
console.log(`${mode === '--check' ? 'Verified' : 'Imported'} Polish data: 1000 given names and 1000 surnames per recorded sex.`);
