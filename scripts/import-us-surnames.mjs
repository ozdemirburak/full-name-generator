import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

// Offline: node scripts/import-us-surnames.mjs [--check]
// Verify against the original Census CSV with --source <Names_2010Census.csv>.
let check = false;
let originalPath;
const args = process.argv.slice(2);
for (let index = 0; index < args.length; index++) {
  if (args[index] === '--check' && !check) check = true;
  else if (args[index] === '--source' && originalPath === undefined && args[index + 1]) originalPath = args[++index];
  else throw new Error('Usage: node scripts/import-us-surnames.mjs [--check] [--source <csv>]');
}
const dataUrl = new URL('./data/', import.meta.url);
const metadata = JSON.parse(readFileSync(new URL('us-census-2010.json', dataUrl), 'utf8'));
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const input = readFileSync(new URL(metadata.snapshot, dataUrl));
if (sha256(input) !== metadata.sha256) throw new Error('Census snapshot checksum mismatch.');
function parse(bytes, original) {
  const [header, ...lines] = bytes.toString('utf8').trimEnd().split(/\r?\n/);
  if (original ? !header.startsWith('name,rank,count,') : header !== 'name,rank,count') throw new Error('Unexpected Census CSV header.');
  return lines.map(line => {
    const fields = line.split(',');
    const [name, rankText, countText] = fields;
    const rank = Number(rankText), count = Number(countText);
    if (fields.length !== (original ? 11 : 3) || !/^[A-Z -]+$/.test(name)
      || !/^\d+$/.test(rankText) || !/^\d+$/.test(countText)
      || !Number.isSafeInteger(rank) || !Number.isSafeInteger(count) || count < 1) throw new Error('Invalid Census row.');
    return { name, rank, count };
  });
}
const rows = parse(input, false);
if (metadata.count !== 1000 || rows.length !== 1000 || new Set(rows.map(row => row.name)).size !== 1000
  || rows.some((row, index) => row.rank < 1 || (index > 0 && (row.rank < rows[index - 1].rank || row.count > rows[index - 1].count)))) {
  throw new Error('Invalid Census surname selection.');
}
if (originalPath !== undefined) {
  const original = readFileSync(originalPath);
  if (sha256(original) !== metadata.sourceSha256) throw new Error('Original Census CSV checksum mismatch.');
  const selected = parse(original, true).filter(row => row.rank > 0).sort((a, b) => a.rank - b.rank).slice(0, metadata.count);
  if (JSON.stringify(selected) !== JSON.stringify(rows)) throw new Error('Census snapshot differs from original source.');
  console.log('Verified the Census snapshot against the original CSV.');
}
const surnames = rows.map(({ name }) => name[0] + name.slice(1).toLowerCase());
const formatted = Array.from({ length: Math.ceil(surnames.length / 10) }, (_, index) =>
  `    ${surnames.slice(index * 10, index * 10 + 10).map(name => `'${name}'`).join(', ')}`);
const output = `/* Data source: ${metadata.source} */
/* Source data licence (publisher): ${metadata.license} */
/* Source data licence URL: ${metadata.licenseUrl} */
/* Credit (optional): ${metadata.attribution} */
/* URL: ${metadata.url} */
/* Selection: First 1000 ranked surnames. See scripts/data/us-census-2010.json for the pinned source and display transformation. */
/* Generated by scripts/import-us-surnames.mjs; do not edit the array manually. */
const americanSurnames = [
${formatted.join(',\n')}
];

export default americanSurnames;
`;
const target = new URL('../src/surnames/us.ts', import.meta.url);
if (check) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('US surnames differ from the pinned source.');
} else writeFileSync(target, output);
console.log(`${check ? 'Verified' : 'Imported'} 1000 US surnames against the pinned Census source.`);
