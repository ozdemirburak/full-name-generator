import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [mode] = process.argv.slice(2);
assert.ok((mode === undefined || mode === '--check') && process.argv.length <= 3,
  'Usage: node scripts/import-it-data.mjs [--check]');
const data = new URL('./data/', import.meta.url);
const display = name => name.replace(/\p{L}[\p{L}\p{M}]*/gu, word => word[0] + word.slice(1).toLowerCase());
const format = values => Array.from({ length: Math.ceil(values.length / 10) }, (_, i) =>
  `        ${values.slice(i * 10, i * 10 + 10).map(name => JSON.stringify(name)).join(', ')}`).join(',\n');

for (const [kind, year, expectedRows, expectedCounts] of [
  ['names', '2025', 400, [192, 179]],
  ['surnames', '2021', 1750, [1732]]
]) {
  const filename = `it-bergamo-${year}-${kind}.json`;
  const metadata = JSON.parse(readFileSync(new URL(filename, data), 'utf8'));
  const bytes = readFileSync(new URL(metadata.snapshot, data));
  assert.equal(createHash('sha256').update(bytes).digest('hex'), metadata.sha256, 'Bergamo source checksum mismatch');
  const rows = JSON.parse(bytes.toString('utf8'));
  assert.equal(rows.length, expectedRows, 'Unexpected Bergamo source row count');
  const given = kind === 'names';
  const field = given ? 'nome' : 'cognome';
  const fields = ['anno', 'cittadinanza', 'frequenza', field, ...(given ? ['genere'] : [])].sort();
  const pools = Array.from({ length: given ? 2 : 1 }, () => new Map());
  const seen = new Set();
  const categoryCounts = new Map();
  for (const row of rows) {
    assert.deepEqual(Object.keys(row).sort(), fields, 'Unexpected Bergamo columns');
    assert.equal(row.anno, year, 'Do not combine multiple reference years');
    assert.ok(['Italiani', 'Stranieri'].includes(row.cittadinanza), 'Unreviewed citizenship category');
    assert.ok(!given || ['Maschi', 'Femmine'].includes(row.genere), 'Unreviewed sex category');
    assert.match(row.frequenza, /^\d+$/);
    const count = Number(row.frequenza);
    assert.ok(Number.isSafeInteger(count) && count >= (given ? 1 : 11), 'Invalid published frequency');
    const name = row[field].normalize('NFC').trim();
    assert.match(name, /^\p{L}[\p{L}\p{M} '\u2019-]+$/u, 'Invalid source name');
    const gender = given && row.genere === 'Femmine' ? 1 : 0;
    const key = JSON.stringify([gender, row.cittadinanza, name]);
    assert.ok(!seen.has(key), 'Duplicate source name within a sex/citizenship category');
    seen.add(key);
    const category = `${gender}:${row.cittadinanza}`;
    categoryCounts.set(category, (categoryCounts.get(category) ?? 0) + 1);
    // The two citizenship categories are disjoint. An unpublished counterpart
    // is unknown, so this is a sum of published counts, not a full city estimate.
    pools[gender].set(name, (pools[gender].get(name) ?? 0) + count);
  }
  if (given) assert.deepEqual([...categoryCounts.values()], [100, 100, 100, 100]);
  const selected = pools.map((pool, index) => {
    assert.equal(pool.size, expectedCounts[index]);
    const values = [...pool].sort((a, b) => b[1] - a[1]
      || Buffer.compare(Buffer.from(a[0]), Buffer.from(b[0]))).map(([name]) => display(name));
    assert.equal(new Set(values).size, values.length, 'Display conversion merged spellings');
    return values;
  });
  const variable = given ? 'italianNames' : 'italianSurnames';
  const array = given ? `{
    0: [\n${format(selected[0])}\n    ],
    1: [\n${format(selected[1])}\n    ]
}` : `[\n${format(selected[0])}\n]`;
  const output = `/* Data source: ${metadata.source} */
/* Source data licence (publisher): ${metadata.license} */
/* Source data licence URL: ${metadata.licenseUrl} */
/* URL: ${metadata.url} */
/* Credit (optional): ${metadata.attribution} */
/* Selection: ${metadata.selection} */
/* Display: ${metadata.display} */
/* Source details and checksums: scripts/data/${filename} */
/* Generated by scripts/import-it-data.mjs; do not edit the arrays manually. */
const ${variable} = ${array};

export default ${variable};
`;
  const target = new URL(`../src/${kind}/it.ts`, import.meta.url);
  if (mode === '--check') assert.equal(readFileSync(target, 'utf8'), output, `Italian ${kind} differ from the reviewed sources`);
  else writeFileSync(target, output);
}
console.log(`${mode === '--check' ? 'Verified' : 'Imported'} Bergamo CC0 data: 192 male names, 179 female names and 1732 shared surnames.`);
