import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { selectAuthorityNames, readRegistryNames } from './authority-data.mjs';

const [mode] = process.argv.slice(2);
assert.ok((mode === undefined || mode === '--check') && process.argv.length <= 3,
  'Usage: node scripts/import-authority-data.mjs [--check]');
const data = new URL('./data/', import.meta.url);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const load = filename => {
  const manifest = JSON.parse(readFileSync(new URL(filename, data), 'utf8'));
  const bytes = readFileSync(new URL(manifest.snapshot, data));
  assert.equal(hash(bytes), manifest.sha256, 'Authority/registry source checksum mismatch');
  return { manifest, bytes, filename };
};
const format = values => Array.from({ length: Math.ceil(values.length / 10) }, (_, i) =>
  `        ${values.slice(i * 10, i * 10 + 10).map(name => JSON.stringify(name)).join(', ')}`).join(',\n');

for (const country of ['at', 'cz', 'de', 'es', 'fi', 'fr', 'gb', 'ie', 'lu', 'nl', 'no']) {
  const sources = {};
  const pools = {};
  const surnamePools = ['cz', 'ie', 'no'].includes(country) ? ['male-surnames', 'female-surnames'] : ['surnames'];
  const authorityPools = country === 'lu' ? surnamePools : ['male', 'female', ...surnamePools];
  for (const pool of authorityPools) {
    const source = load(`${country}-gnd-2026-${pool}.json`);
    const { manifest, bytes } = source;
    assert.equal(manifest.country, country);
    assert.equal(manifest.pool, pool);
    assert.equal(hash(manifest.query), manifest.querySha256, 'Changed recorded SPARQL query');
    const response = JSON.parse(bytes.toString('utf8'));
    assert.equal(response.results.bindings.length, manifest.sourceRowCount, 'Unexpected authority row count');
    const selection = selectAuthorityNames(response, pool);
    assert.equal(selection.validStringCount, manifest.validStringCount, 'Unexpected valid authority count');
    assert.equal(selection.names.length, manifest.selectedCount, 'Unexpected selected authority count');
    sources[pool] = source;
    pools[pool] = selection.names;
  }
  if (country === 'lu') {
    const source = load('lu-rnpp-2020-names.json');
    const { manifest, bytes } = source;
    const evidence = JSON.parse(readFileSync(new URL(manifest.rights.snapshot, data), 'utf8'));
    const resource = evidence.resources.find(item => item.url === manifest.requestUrl);
    assert.ok(resource, 'RNPP resource is absent from official metadata');
    assert.equal(resource.checksum.type, 'sha1');
    assert.equal(createHash('sha1').update(bytes).digest('hex'), resource.checksum.value, 'RNPP publisher checksum mismatch');
    const [male, female] = readRegistryNames(bytes);
    assert.equal(male.length + female.length, manifest.sourceRowCount);
    assert.deepEqual([male.length, female.length], [manifest.counts[0], manifest.counts[1]]);
    pools.male = male;
    pools.female = female;
    sources.male = source;
    sources.female = source;
  }
  for (const kind of ['names', 'surnames']) {
    const given = kind === 'names';
    const keys = given ? ['male', 'female'] : surnamePools;
    const selected = keys.map(key => sources[key]);
    const unique = [...new Map(selected.map(source => [source.filename, source])).values()];
    const comments = unique.map(({ manifest, filename }) => `/* Data source: ${manifest.source} */
/* Source data licence (publisher): ${manifest.license} */
/* Source data licence URL: ${manifest.licenseUrl} */
/* URL: ${manifest.url} */
/* Credit (optional): ${manifest.attribution} */
/* Selection: ${manifest.selection} */
/* Display: ${manifest.display} */
/* Source details and checksums: scripts/data/${filename} */`).join('\n');
    const variable = `${country}${given ? 'Names' : 'Surnames'}`;
    const array = keys.length === 2 ? `{
    0: [\n${format(pools[keys[0]])}\n    ],
    1: [\n${format(pools[keys[1]])}\n    ]
}` : `[\n${format(pools[keys[0]])}\n]`;
    const output = `${comments}
/* Generated by scripts/import-authority-data.mjs; do not edit the arrays manually. */
const ${variable} = ${array};

export default ${variable};
`;
    const target = new URL(`../src/${kind}/${country}.ts`, import.meta.url);
    if (mode === '--check') assert.equal(readFileSync(target, 'utf8'), output, `${country} ${kind} differ from reviewed sources`);
    else writeFileSync(target, output);
  }
  const surnameCounts = surnamePools.length === 2
    ? `${pools['male-surnames'].length} male / ${pools['female-surnames'].length} female surnames`
    : `${pools.surnames.length} shared surnames`;
  console.log(`${mode === '--check' ? 'Verified' : 'Imported'} ${country.toUpperCase()} CC0 sample: ${pools.male.length} male, ${pools.female.length} female, ${surnameCounts}.`);
}
